def quest(qid):
    return QUESTS.get(int(qid))


def step_of(qid, index):
    q = QUESTS.get(int(qid))
    if not q:
        return None
    steps = q['steps']
    if 0 <= index < len(steps):
        return steps[index]
    return None


def start_quests_at(mapid, npc_name):
    """该 (map, npc) 能开启的**全部**主线 qid，按剧情编号升序。

    返回列表而不是单个 qid：同一个 NPC 可能是多条剧情的领取人
    （例如金大有管 7 和 12，龙蛇老人管 10 和 15）。只返回第一条会让
    「前一条做完后，同一个 NPC 再也发不出下一条」。
    """
    out = [qid for qid, q in QUESTS.items()
           if q['start_map'] == mapid and q['start_npc'] == npc_name]
    return sorted(out, key=lambda x: QUESTS[x]['no'])


def start_quest_at(mapid, npc_name):
    """兼容旧调用：只返回按编号最近的那一条（新代码请用 start_quests_at）。"""
    ids = start_quests_at(mapid, npc_name)
    return ids[0] if ids else None


def prev_of(qid):
    """该剧情要求的**已完成**前置 qid 集合（资料一览表的「必须条件」栏）。"""
    return tuple(int(x) for x in (QUESTS.get(int(qid), {}).get('prev') or ()))


def npc_of_step(mapid, npc_name, qid, index):
    st = step_of(qid, index)
    if not st:
        return False
    return st['map'] == mapid and st['npc'] == npc_name


def spawns_for(mapid):
    return [s for s in NPC_SPAWNS if s[0] == mapid]
