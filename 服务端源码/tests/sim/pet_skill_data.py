def get(sid, limit=80):
    """按 id 取技能信息；未知 id 返回 None（不抛、不编造名字）。"""
    try:
        info = PET_SKILL_INFO.get(int(sid))
    except (TypeError, ValueError):
        return None
    if info is None:
        return None
    name, tid, desc, fp, mp, hp = info
    return {
        'sid': int(sid), 'name': name, 'type': tid,
        'type_name': SKILL_TYPES.get(tid, u'?'),
        'desc': desc[:limit], 'fpneed': fp, 'mpneed': mp, 'hpneed': hp,
    }


def known(sid):
    """id 是否在本版客户端的技能表里（权威白名单）。"""
    try:
        return int(sid) in PET_SKILL_INFO
    except (TypeError, ValueError):
        return False


def active_ids():
    """能在宠物招式菜单里出现的 id（type 1/2）；被动不算。"""
    return sorted(k for k, v in PET_SKILL_INFO.items() if v[1] in (1, 2))
